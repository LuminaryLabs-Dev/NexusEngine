import assert from "node:assert/strict";
import {createLoopCoordination} from "../../src/core-domains/agent/loop/coordination/index.js";
const c=createLoopCoordination();c.setParentBudget("root",{maxSteps:10,maxModelCalls:6});
c.delegate({delegationId:"d",parentLoopId:"root",childLoopId:"child",goalRef:"goal",budgetAllocation:{maxSteps:4,maxModelCalls:2},authority:["read"],parentAuthority:["read","write"]});
assert.throws(()=>c.delegate({delegationId:"d2",parentLoopId:"root",childLoopId:"bad",goalRef:"goal",budgetAllocation:{maxSteps:7,maxModelCalls:5}}));
c.consume("child",{steps:2,modelCalls:1});c.complete("child",{ok:true,receiptRef:"receipt"});
assert.equal(c.join("root").accepted,true);
console.log("Coordination budget inheritance passed");
const restored=createLoopCoordination();
assert.deepEqual(restored.restore(c.snapshot()),c.snapshot());
assert.deepEqual(restored.join('root'),c.join('root'));
const retained=restored.snapshot(),cycle=structuredClone(retained);
cycle.children[0].parentLoopId='child';
assert.throws(()=>restored.restore(cycle),/cycle/);
assert.deepEqual(restored.snapshot(),retained);
const bad=structuredClone(retained);bad.budgets.push(bad.budgets[0]);
assert.throws(()=>restored.restore(bad));
const deterministic=createLoopCoordination();deterministic.setParentBudget('r',{maxSteps:2,maxModelCalls:0});
deterministic.delegate({delegationId:'d0',parentLoopId:'r',childLoopId:'c0',goalRef:'g',budgetAllocation:{maxSteps:2,maxModelCalls:0}});
const resumed=createLoopCoordination();resumed.restore(deterministic.snapshot());resumed.consume('c0',{steps:1});resumed.complete('c0',{ok:true,receiptRef:'proof'});
assert.equal(resumed.join('r').accepted,true);
console.log('Coordination atomic restore and deterministic allocation passed');
const nested=createLoopCoordination();
nested.setParentBudget('p',{maxSteps:10,maxModelCalls:0});
nested.delegate({delegationId:'n1',parentLoopId:'p',childLoopId:'n',goalRef:'g',budgetAllocation:{maxSteps:8,maxModelCalls:0}});
nested.delegate({delegationId:'n2',parentLoopId:'n',childLoopId:'leaf',goalRef:'g',budgetAllocation:{maxSteps:5,maxModelCalls:0}});
const nestedSnapshot=nested.snapshot();
assert.deepEqual(createLoopCoordination().restore(nestedSnapshot),nestedSnapshot);
const forged=structuredClone(nestedSnapshot);forged.budgets.find(([id])=>id==='n')[1].steps=8;
assert.throws(()=>createLoopCoordination().restore(forged),/Nested/);
assert.throws(()=>nested.delegate({delegationId:'n1',parentLoopId:'p',childLoopId:'other',goalRef:'g',budgetAllocation:{maxSteps:1,maxModelCalls:0}}),/duplicate/);
const deterministicChildren=createLoopCoordination();deterministicChildren.setParentBudget('droot',{maxSteps:3,maxModelCalls:0});
deterministicChildren.delegate({delegationId:'dd',parentLoopId:'droot',childLoopId:'dc',goalRef:'goal',budgetAllocation:{maxSteps:2,maxModelCalls:0}});
deterministicChildren.consume('dc',{steps:1,modelCalls:0});deterministicChildren.complete('dc',{ok:true,receiptRef:'deterministic-proof'});assert.equal(deterministicChildren.join('droot').accepted,true);
