import assert from "node:assert/strict";
import { createEngine } from "../../src/index.js";
import { createDataKit } from "../../src/core-domains/runtime/data/kits/data-kit/index.js";
import { createObservationHistoryKit } from "../../src/core-domains/runtime/data/observation/kits/observation-history-kit/index.js";
const kit = createObservationHistoryKit({ retention: { maxFrames: 2, maxBytes: 4096 } });
const engine = createEngine({ kits: [createDataKit(), kit] });
engine.installKit(kit);
const history = engine.n.observationHistory;
const record = frame => ({ sessionId: "test", epoch: 0, sourceFrame: frame, committed: true, domains: { test: frame } });
history.appendCommitted(record(1)); const before = history.getSnapshot();
history.appendCommitted(record(1)); assert.deepEqual(history.getSnapshot(), before);
assert.throws(() => history.appendCommitted({ ...record(1), domains: {} }), /Conflicting/);
assert.throws(() => history.appendCommitted({ ...record(2), committed: false }));
history.appendCommitted(record(2)); history.appendCommitted(record(3));
assert.equal(history.getFrame(record(1)), null); assert.equal(history.list().length, 2);
assert.throws(() => history.list({ after: record(1) }), /evicted/);
assert.throws(() => history.appendCommitted(record(0)), /Stale/);
const saved = history.getSnapshot(); history.reset(); assert.equal(history.list().length, 0);
history.loadSnapshot(saved); assert.deepEqual(history.getSnapshot(), saved);
assert.throws(() => history.loadSnapshot({ ...saved, bytes: 0 }));
history.setRetention({ maxFrames: 1, maxBytes: 4096 }); assert.equal(history.list().length, 1);
assert.throws(() => history.appendCommitted({ ...record(4), huge: "x".repeat(5000) }));
history.appendCommitted({ ...record(0), epoch: 1 });
assert.throws(() => history.appendCommitted(record(5)), /Stale/);
console.log("observation history: PASS");
