import assert from "node:assert/strict";
import {createComputeKit,createEngine} from "../helpers/public-package-surface.mjs";
import {createModelKit,createModelRegistry,createModelDescriptor} from "../../src/core-domains/compute/model/kits/model-kit/index.js";
import {createInferenceRequest,executeInference} from "../../src/core-domains/inference/index.js";
import {createInferenceProviderPool} from "../../src/core-domains/inference/provider/index.js";
const registry=createModelRegistry();registry.register(createModelDescriptor({id:"mock",kind:"classifier"}));
assert.equal(registry.get("mock").kind,"classifier");
const engine=createEngine({kits:[createComputeKit(),createModelKit({models:[{id:"fixture",kind:"classifier"}]})]});
assert.equal(engine.n.model.getModels()[0].id,"fixture");
assert.equal(typeof engine.n.model.infer,"undefined","Model Kit no longer executes inference");
const pool=createInferenceProviderPool({providers:[{id:"local",protocol:"local"}],instances:[{id:"fixture",providerId:"local",models:["fixture"],capacity:1,free:true}]});
let executions=0;
const request=createInferenceRequest({id:"fixture-request",modelId:"fixture",input:{text:"ok"}});
const result=await executeInference({request,pool,adapter:{infer:async({request})=>{executions++;return {status:"ok",output:{label:request.input.text},usage:{input_tokens:2,output_tokens:3}};}}});
assert.equal(result.status,"ok");assert.equal(result.output.label,"ok");
assert.equal(result.usage.output_tokens,3);assert.equal(executions,1);
assert.equal(pool.snapshot().leases.length,0);
console.log("model registry and canonical inference smoke ok");
