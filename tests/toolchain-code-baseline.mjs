import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync, readFileSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const directory = mkdtempSync(path.join(tmpdir(), 'nexus-boundary-baseline-'));
const archive = spawnSync('git', ['archive', '--format=tar', '081fea1cdd9ca1662bc15116e7174d9c27821630', 'src', 'scripts/check-core-boundaries.mjs', 'package.json', '.gitignore', 'tests/core-domains/core-authoring-public.mjs'], { maxBuffer: 64 * 1024 * 1024 });
assert.equal(archive.status, 0);
const extracted = spawnSync('tar', ['-xf', '-', '-C', directory], { input: archive.stdout });
assert.equal(extracted.status, 0);
assert.equal(spawnSync('git', ['init', '--quiet', directory]).status, 0);
symlinkSync(path.resolve('node_modules'),path.join(directory,'node_modules'));
const baseline = spawnSync(process.execPath, [path.join(directory, 'scripts/check-core-boundaries.mjs')], { encoding: 'utf8' });
const candidate = spawnSync(process.execPath, ['scripts/check-core-boundaries.mjs'], { encoding: 'utf8' });
const findings = r => [...new Set((r.stderr ?? '').match(/^src\/[^\r\n]+/gm) ?? [])].sort();
const report = { baseline: '081fea1cdd9ca1662bc15116e7174d9c27821630', baselineStatus: baseline.status === 0 ? 'PASS' : 'FAIL', candidateStatus: candidate.status === 0 ? 'PASS' : 'FAIL', baselineFindings: findings(baseline), candidateFindings: findings(candidate) };
mkdirSync('Auditor/runs/baseline', { recursive: true });
writeFileSync('Auditor/runs/baseline/boundaries.json', JSON.stringify(report, null, 2));
writeFileSync('Auditor/runs/baseline/stderr.log', baseline.stderr ?? '');
assert.equal(baseline.status, 1);
assert.equal(candidate.status, 1);
assert.deepEqual(report.candidateFindings, report.baselineFindings);
assert(report.baselineFindings.length > 0);
console.log(JSON.stringify({ ...report, newBoundaryFindings: [] }, null, 2));

const publicBaseline=spawnSync(process.execPath,[path.join(directory,'tests/core-domains/core-authoring-public.mjs')],{encoding:'utf8'});
assert.equal(publicBaseline.status,1);assert.match(publicBaseline.stderr,/authoring-import-registry-kit/);assert.match(publicBaseline.stderr,/authoring-import-validation-kit/);
writeFileSync('Auditor/runs/baseline/authoring-public.stderr.log',publicBaseline.stderr);
console.log('Published baseline also fails the existing Authoring import-registry ownership assertion.');
rmSync(directory,{recursive:true,force:true});
